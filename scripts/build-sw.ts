import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { sourceHash } from './source-hash';

const root = join(import.meta.dir, '..');
const target = join(root, 'src/server/embedded.ts');

async function bundle(entry: string): Promise<string> {
	const result = await Bun.build({
		entrypoints: [join(root, entry)],
		target: 'browser',
		format: 'iife',
		minify: true
	});
	if (!result.success) {
		for (const log of result.logs) console.error(log);
		process.exit(1);
	}
	return (await result.outputs[0]?.text()) ?? '';
}

const hash = sourceHash(root);

if (process.argv.includes('--check')) {
	const current = /SOURCE_HASH = '([0-9a-f]*)'/.exec(readFileSync(target, 'utf8'))?.[1];
	if (current !== hash) {
		console.error('src/server/embedded.ts is out of date; run: bun run build:sw');
		process.exit(1);
	}
	process.exit(0);
}

const sw = await bundle('src/sw/core.ts');
const client = await bundle('src/client/entry.ts');

writeFileSync(
	target,
	[
		'/** the service worker core, generated by `bun run build:sw`; never edit by hand */',
		`export const SW_CORE = ${JSON.stringify(sw)};`,
		'',
		'/** the page runtime, generated by `bun run build:sw`; never edit by hand */',
		`export const CLIENT_CORE = ${JSON.stringify(client)};`,
		'',
		'/** hash of the sources both bundles were built from; a test fails when it drifts */',
		`export const SOURCE_HASH = '${hash}';`,
		''
	].join('\n')
);
console.log(`embedded.ts: sw ${sw.length} bytes, client ${client.length} bytes`);
